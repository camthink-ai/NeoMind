//! OpenAPI schema generation via utoipa.
//!
//! Every routed handler carries a `#[utoipa::path]` annotation and is
//! registered in `paths()` below; the spec is served at
//! `GET /api/docs/openapi.json` and rendered by the Scalar console at
//! `/api/docs`. Handlers behind wildcard routes (`/api/images/*path`,
//! `/api/extensions/:id/assets/*asset_path`, `/api/share/:token/proxy/*path`,
//! `/api/docs/*rest`) are not representable as OpenAPI templates and stay
//! discoverable via `/api/docs/routes.json` (the CI-enforced route index).
//!
//! Adding an endpoint: derive `utoipa::path` on the handler (params,
//! request body, responses with the shapes from the handler's DTOs), add it
//! to `paths()` below, and extend the drift test if it's a new router.

